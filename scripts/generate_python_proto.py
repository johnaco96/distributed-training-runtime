#!/usr/bin/env python3
"""Generate Python protobuf/gRPC modules for the runtime control-plane API."""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
PROTO_DIR = REPO_ROOT / "proto"
PROTO_FILE = PROTO_DIR / "runtime.proto"
OUT_DIR = REPO_ROOT / "python" / "dtruntime" / "generated"
PB2_GRPC_FILE = OUT_DIR / "runtime_pb2_grpc.py"

_TIMESTAMP_PROTO = '''syntax = "proto3";
package google.protobuf;
option csharp_namespace = "Google.Protobuf.WellKnownTypes";
option cc_enable_arenas = true;
option go_package = "google.golang.org/protobuf/types/known/timestamppb";
option java_package = "com.google.protobuf";
option java_outer_classname = "TimestampProto";
option java_multiple_files = true;
option objc_class_prefix = "GPB";
message Timestamp {
  int64 seconds = 1;
  int32 nanos = 2;
}
'''


def _run_grpc_tools() -> bool:
    command = [
        sys.executable,
        "-m",
        "grpc_tools.protoc",
        "-I",
        str(PROTO_DIR),
        f"--python_out={OUT_DIR}",
        f"--grpc_python_out={OUT_DIR}",
        str(PROTO_FILE),
    ]
    try:
        subprocess.run(command, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except (FileNotFoundError, subprocess.CalledProcessError):
        return False
    return True


def _run_system_protoc() -> None:
    protoc = shutil.which("protoc")
    if protoc is None:
        raise RuntimeError("grpcio-tools is unavailable and protoc was not found on PATH")

    with tempfile.TemporaryDirectory() as tmp:
        include_root = Path(tmp)
        timestamp = include_root / "google" / "protobuf" / "timestamp.proto"
        timestamp.parent.mkdir(parents=True, exist_ok=True)
        timestamp.write_text(_TIMESTAMP_PROTO, encoding="utf-8")
        subprocess.run(
            [
                protoc,
                "-I",
                str(PROTO_DIR),
                "-I",
                str(include_root),
                f"--python_out={OUT_DIR}",
                str(PROTO_FILE),
            ],
            check=True,
        )


def _patch_grpc_import() -> None:
    text = PB2_GRPC_FILE.read_text(encoding="utf-8")
    text = text.replace("import runtime_pb2 as runtime__pb2", "from . import runtime_pb2 as runtime__pb2")
    PB2_GRPC_FILE.write_text(text, encoding="utf-8")


def _parse_rpc_methods(proto_text: str) -> list[tuple[str, str, str]]:
    service_match = re.search(r"service\s+CoordinatorService\s*\{(?P<body>.*?)\n\}", proto_text, re.S)
    if service_match is None:
        raise RuntimeError("CoordinatorService was not found in proto/runtime.proto")
    return re.findall(
        r"rpc\s+(\w+)\s*\(\s*(\w+)\s*\)\s*returns\s*\(\s*(\w+)\s*\)\s*;",
        service_match.group("body"),
    )


def _generate_minimal_grpc_client() -> None:
    methods = _parse_rpc_methods(PROTO_FILE.read_text(encoding="utf-8"))
    lines = [
        "# Generated by scripts/generate_python_proto.py. DO NOT EDIT!",
        '"""Client-side gRPC bindings for proto/runtime.proto."""',
        "",
        "import grpc",
        "",
        "from . import runtime_pb2 as runtime__pb2",
        "",
        "",
        "class CoordinatorServiceStub(object):",
        '    """CoordinatorService control-plane client stub."""',
        "",
        "    def __init__(self, channel):",
        '        """Constructor.',
        "",
        "        Args:",
        "            channel: A grpc.Channel.",
        '        """',
    ]
    for name, request, response in methods:
        lines.extend(
            [
                f"        self.{name} = channel.unary_unary(",
                f"            '/runtime.v1.CoordinatorService/{name}',",
                f"            request_serializer=runtime__pb2.{request}.SerializeToString,",
                f"            response_deserializer=runtime__pb2.{response}.FromString,",
                "        )",
            ]
        )
    lines.append("")
    PB2_GRPC_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    if _run_grpc_tools():
        _patch_grpc_import()
    else:
        _run_system_protoc()
        _generate_minimal_grpc_client()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
